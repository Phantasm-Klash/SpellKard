def ts_str(value):
    """JSON string is valid TS string literal for our data (ASCII + CJK)."""
    return json.dumps(value, ensure_ascii=False)


def gen_bullet_kind(contract):
    kinds = sorted(contract["bullet_kinds"], key=lambda k: k["type"])
    species = sorted(contract["bullet_species"], key=lambda s: min(s["types"]))
    lines = [HEADER, ""]
    lines.append("/**")
    lines.append(" * `kEnemyBullet` 枚举的客户端镜像。数值与原版 / 服务端**逐位一致**，")
    lines.append(" * 客户端用它索引图集帧（见 `layaide/assets/resources/tna/index.json`）。")
    lines.append(" */")
    lines.append("")
    lines.append("export interface BulletKindInfo {")
    lines.append("  /** 原版 `kEnemyBullet` 枚举值。 */")
    lines.append("  readonly type: number;")
    lines.append("  /** 图集帧名，例如 `kusabi_01.png`。 */")
    lines.append("  readonly frame: string;")
    lines.append("  /** 图集名，例如 `bulletlist01`。 */")
    lines.append("  readonly atlas: string;")
    lines.append("}")
    lines.append("")
    lines.append("export interface BulletSpeciesInfo {")
    lines.append("  readonly species: string;")
    lines.append("  readonly types: readonly number[];")
    lines.append("}")
    lines.append("")
    lines.append("export const BULLET_KIND_MIN = %d;" % min(k["type"] for k in kinds))
    lines.append("export const BULLET_KIND_MAX = %d;" % max(k["type"] for k in kinds))
    lines.append("export const BULLET_KIND_COUNT = %d;" % len(kinds))
    lines.append("")
    lines.append("/** 216 个弹种，按 type 升序。 */")
    lines.append("export const BULLET_KINDS: readonly BulletKindInfo[] = [")
    for k in kinds:
        lines.append("  { type: %d, frame: %s, atlas: %s }," % (k["type"], ts_str(k["frame"]), ts_str(k["atlas"])))
    lines.append("];")
    lines.append("")
    lines.append("const KIND_BY_TYPE = new Map<number, BulletKindInfo>();")
    lines.append("for (const info of BULLET_KINDS) {")
    lines.append("  KIND_BY_TYPE.set(info.type, info);")
    lines.append("}")
    lines.append("")
    lines.append("/** 查弹种元数据；越界返回 `undefined`。 */")
    lines.append("export function bulletKindInfo(type: number): BulletKindInfo | undefined {")
    lines.append("  return KIND_BY_TYPE.get(type);")
    lines.append("}")
    lines.append("")
    lines.append("/** 是否为合法的 `kEnemyBullet` 值。 */")
    lines.append("export function isBulletKind(type: number): boolean {")
    lines.append("  return KIND_BY_TYPE.has(type);")
    lines.append("}")
    lines.append("")
    lines.append("/** 43 个子弹物种（每物种 1..9 个连续 type）。 */")
    lines.append("export const BULLET_SPECIES: readonly BulletSpeciesInfo[] = [")
    for s in species:
        types = ", ".join(str(t) for t in sorted(s["types"]))
        lines.append("  { species: %s, types: [%s] }," % (ts_str(s["species"]), types))
    lines.append("];")
    lines.append("")
    return "\n".join(lines) + "\n"


def gen_motion_table(contract):
    motions = sorted(contract["bullet_motions"], key=lambda m: m["func"])
    lines = [HEADER, ""]
    lines.append("/**")
    lines.append(" * 79 个 `EnemyBullet::bulletFuncN` 的元数据（编号 / 行为族 / 逆向公式）。")
    lines.append(" * 数值语义见 `rev/patterns/bullet_funcs_disasm.md`。角度单位为**度**。")
    lines.append(" */")
    lines.append("")
    lines.append("export interface BulletMotionInfo {")
    lines.append("  /** `bulletFunc` 编号（原版状态号 1..85 的子集）。 */")
    lines.append("  readonly func: number;")
    lines.append("  /** 逆向文档给出的行为族名（中文）。 */")
    lines.append("  readonly family: string;")
    lines.append("  /** 逆向文档给出的族分组（中文，可能为空串）。 */")
    lines.append("  readonly group: string;")
    lines.append("  /** 逆向公式/语义描述。 */")
    lines.append("  readonly formula: string;")
    lines.append("  /** 原版函数地址（诊断用）。 */")
    lines.append("  readonly addr: string;")
    lines.append("}")
    lines.append("")
    lines.append("export const BULLET_MOTION_COUNT = %d;" % len(motions))
    lines.append("")
    lines.append("export const BULLET_MOTIONS: readonly BulletMotionInfo[] = [")
    for m in motions:
        lines.append("  {")
        lines.append("    func: %d," % m["func"])
        lines.append("    family: %s," % ts_str(m.get("family", "")))
        lines.append("    group: %s," % ts_str(m.get("family_group", "")))
        lines.append("    formula: %s," % ts_str(m.get("formula", "")))
        lines.append("    addr: %s," % ts_str(m.get("addr", "")))
        lines.append("  },")
    lines.append("];")
    lines.append("")
    lines.append("const MOTION_BY_FUNC = new Map<number, BulletMotionInfo>();")
    lines.append("for (const info of BULLET_MOTIONS) {")
    lines.append("  MOTION_BY_FUNC.set(info.func, info);")
    lines.append("}")
    lines.append("")
    lines.append("export function bulletMotionInfo(func: number): BulletMotionInfo | undefined {")
    lines.append("  return MOTION_BY_FUNC.get(func);")
    lines.append("}")
    lines.append("")
    return "\n".join(lines) + "\n"


