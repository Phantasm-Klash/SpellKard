def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--contract", default=DEFAULT_CONTRACT)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    with open(args.contract, encoding="utf-8") as f:
        contract = json.load(f)

    outputs = {
        "bullet_kind.ts": gen_bullet_kind(contract),
        "bullet_motion_table.ts": gen_motion_table(contract),
        "player_loadout.ts": gen_player_loadout(contract),
    }

    os.makedirs(args.out, exist_ok=True)
    drift = []
    for name, content in outputs.items():
        path = os.path.join(args.out, name)
        if args.check:
            existing = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if existing != content:
                drift.append(name)
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(content)
            print("wrote %s (%d bytes)" % (name, len(content)))

    if args.check:
        if drift:
            print("DRIFT: %s" % ", ".join(drift))
            sys.exit(1)
        print("danmaku TS data in sync.")


if __name__ == "__main__":
    main()
