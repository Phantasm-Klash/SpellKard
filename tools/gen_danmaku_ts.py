def gen_player_loadout(contract):
    shots = contract["player_shots"]
    lines = [HEADER, ""]
    lines.append("/**")
    lines.append(" * 自机武装数据表：52 个射击（契约）+ 13 个炸弹（`rev/patterns/player_shots_disasm.md`）。")
    lines.append(" * 角度单位 = 度（90° = 正上方）。")
    lines.append(" */")
    lines.append("")
    lines.append("export interface PlayerShotSpec {")
    lines.append("  readonly name: string;")
    lines.append("  readonly chara: string;")
    lines.append("  readonly mode: string;")
    lines.append("  readonly variant: number;")
    lines.append("  /** 每轮子弹数。 */")
    lines.append("  readonly volleyN: number;")
    lines.append("  /** 逐发角度（度）；不足时按 `volleyN` 轮转。 */")
    lines.append("  readonly anglesDeg: readonly number[];")
    lines.append("  /** 初速。 */")
    lines.append("  readonly speedN: number;")
    lines.append("  /** `kMyBullet` 贴图 type（0..83）。 */")
    lines.append("  readonly texTypes: readonly number[];")
    lines.append("  /** 逆向是否已完整解析（false = 有未确定字段）。 */")
    lines.append("  readonly resolved: boolean;")
    lines.append("}")
    lines.append("")
    lines.append("export const PLAYER_SHOT_COUNT = %d;" % len(shots))
    lines.append("")
    lines.append("export const PLAYER_SHOTS: readonly PlayerShotSpec[] = [")
    for s in shots:
        angles = ", ".join(repr(float(a)) for a in s.get("angles_deg", []))
        tex = ", ".join(str(int(t)) for t in s.get("tex_types", []))
        speed = s.get("speed_n")
        speed_s = "0" if speed is None else repr(float(speed))
        lines.append("  {")
        lines.append("    name: %s, chara: %s, mode: %s, variant: %d," %
                     (ts_str(s["name"]), ts_str(s["chara"]), ts_str(s["mode"]), int(s["variant"])))
        lines.append("    volleyN: %d, anglesDeg: [%s], speedN: %s," %
                     (int(s["volley_n"]), angles, speed_s))
        lines.append("    texTypes: [%s], resolved: %s," % (tex, "true" if s.get("resolved") else "false"))
        lines.append("  },")
    lines.append("];")
    lines.append("")
    lines.append("export interface PlayerBombPart {")
    lines.append("  /** `kMyBullet` 炸弹 type（62..82）。 */")
    lines.append("  readonly type: number;")
    lines.append("  readonly texture: string;")
    lines.append("  /** 构造第 1 参，疑似伤害。 */")
    lines.append("  readonly damage: number;")
    lines.append("  /** 初始角度（度）；`null` = 逆向未捕获。 */")
